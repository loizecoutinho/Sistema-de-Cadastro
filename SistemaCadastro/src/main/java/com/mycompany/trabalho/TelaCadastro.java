    private void jButtonExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonExcluirActionPerformed
       // TODO add your handling code here:
        String matricula = jFormattedTextFieldMatricula.getText().trim();
        //verifica se a matricula na jTextField é valida ou se foi preenchida
        if (matricula.trim().isEmpty()) {
            jOptionPaneAlerta.showMessageDialog(this, "Matrícula é obrigatória!",
                "Aviso", jOptionPaneAlerta.WARNING_MESSAGE);
            return;
        }

        boolean removido = excluirAluno(matricula); // chama a função e recebe o seu retorno

        //utiliza o valor do retorno para verificação
        if(removido){
            jOptionPaneAlerta.showMessageDialog(this, "Matricula " + matricula +"removida!",
                "Aluno Removido", jOptionPaneAlerta.INFORMATION_MESSAGE);
            ArquivoCSV.salvarAluno(listaAlunos);
            return;
        }
        jOptionPaneAlerta.showMessageDialog(this, "Aluno com matrícula " + matricula + " não encontrado.",
            "Aviso", jOptionPaneAlerta.INFORMATION_MESSAGE);
    }//GEN-LAST:event_jButtonExcluirActionPerformed

