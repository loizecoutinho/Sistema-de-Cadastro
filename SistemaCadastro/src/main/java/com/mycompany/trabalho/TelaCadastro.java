    /*Metodo para exclusão de um aluno da lista
      Classe RemocaoAlunoDAO que implementa a Interface AlunoDAO*/
    public boolean excluirAluno(String matricula){
        EntityManager em = null;
        try {
                em = JPAUtil.getEntityManagerFactory().createEntityManager();
                em.getTransaction().begin();

                //Encontra o aluno no banco de dados
                Aluno alunoRemover = em.find(Aluno.class, matricula);

                if (alunoRemover != null) {
                    em.remove(alunoRemover);

                    em.getTransaction().commit();

                    AlunoDAO dao = new RemocaoAlunoDAO();
                    Aluno alunoLista = null;
                    for (Aluno alunoTemp : listaAlunos) {
                        if (matricula.equals(alunoTemp.getMatr())) {
                            alunoLista = alunoTemp;
                            break;
                        }
                    }
                    if (alunoLista != null) {
                        dao.removerAluno(listaAlunos, alunoLista);
                        quantTotal--;
                    }
                    return true;
                    
                } else {
                    em.getTransaction().rollback();
                    return false;
                }

            } catch (Exception e) {
                System.err.println("Erro ao excluir aluno: " + e.getMessage());
                e.printStackTrace();
                // Desfaz a transação
                if (em != null && em.getTransaction().isActive()) {
                    em.getTransaction().rollback();
                }
                return false;
            } finally {
                if (em != null) {
                    em.close();
                }
            }
    }
     
