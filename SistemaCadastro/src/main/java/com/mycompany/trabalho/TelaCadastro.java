    private void jButtonInserirPosicaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonInserirPosicaoActionPerformed
        // TODO add your handling code here:
        EntityManager em = null;
        try {
            //para formatação da data
            DateTimeFormatter fmt = DateTimeFormatter.ofPattern("dd/MM/yyyy");

            String nome = jTextFieldNome.getText().trim();
            String matricula = jFormattedTextFieldMatricula.getText().trim();
            String dataNascTexto = jFormattedTextFieldDataNasc.getText().trim();
            String cpf = jFormattedTextFieldCpf.getText().trim();
            String telefone = jFormattedTextFieldTelefone.getText().trim();

            boolean temCampoVazio = existeCamposVazios(nome,matricula,dataNascTexto,cpf,telefone);
            if (temCampoVazio){
                return;
            }

            // Conversão da data e inserção de idade no campo jTextFieldIdade
            LocalDate dataNasc = LocalDate.parse(dataNascTexto, fmt);
            int idade = calculaIdade(dataNasc);
            jTextFieldIdade.setText(Integer.toString(idade));

            //Instanciando Aluno
            Aluno alunoParaInserir = new Aluno(matricula,nome,dataNasc,telefone,cpf, idade);

            //usando JOptionPane para pedir a posição onde o usuario quer inserir o aluno
            String inputPos = jOptionPaneInserir.showInputDialog(
                this, "Digite a posição onde deseja inserir o aluno:",
                "Inserir em Posição", // Título da caixa de diálogo
                jOptionPaneInserir.QUESTION_MESSAGE
            ); //"this" é a TelaCadastro

            // Verifica se o usuário clicou "Cancelar" ou não digitou nada
            if (inputPos != null && !inputPos.isEmpty()) {
                // Converte o texto para um número inteiro
                int pos = Integer.parseInt(inputPos);
                    //inserçaõ no banco
                try{
                   em = JPAUtil.getEntityManagerFactory().createEntityManager();
                   em.getTransaction().begin();
                   em.persist(alunoParaInserir);
                   em.getTransaction().commit();
                }catch(RollbackException e){
                    jOptionPaneAlerta.showMessageDialog(this, "Erro ao salvar no banco: A Matrícula '" + matricula + "' já existe!", "Erro de Duplicidade", JOptionPane.ERROR_MESSAGE);
                    return;
                }catch (Exception e) {
                    jOptionPaneAlerta.showMessageDialog(this, "Erro inesperado ao conectar no banco: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
                    return;
                }finally{
                    if (em != null) {
                        em.close();
                    }
                }
                // Chama o metodo para inserção no csv
                inserePosicao(pos, alunoParaInserir);
                ArquivoCSV.salvarAluno(listaAlunos);
                // Mostrando sucesso para o usuário
                jOptionPaneInserir.showMessageDialog(this, "Aluno inserido com sucesso na posição " + pos + "!", "Sucesso", jOptionPaneInserir.INFORMATION_MESSAGE);
            } else {
                jOptionPaneInserir.showMessageDialog(this, "Operação de inserção cancelada.", "Aviso", jOptionPaneInserir.WARNING_MESSAGE);
            }
        } catch (NumberFormatException e){//verifica se a informação condiz com o tipo pedido
            jOptionPaneAlerta.showMessageDialog(this, "Formato inválido",
                "Erro", jOptionPaneAlerta.ERROR_MESSAGE);
        } catch (IllegalArgumentException e) {
            jOptionPaneAlerta.showMessageDialog(this, "Erro: " + e.getMessage(),
                "Erro", jOptionPaneAlerta.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonInserirPosicaoActionPerformed

